"""Fit controlled/dump entry + exit xG values (Task 4.2) from the corpus.

For each inferred zone entry, sum the xG (via `fit_shot_xg`) of shots taken
by the entering team within `entry_window_s` seconds after it. Average per
entry type (controlled vs dump) -> the per-entry xG value. Exit value is the
mean post-exit xG within the same window (a controlled exit springs a rush).

Run: uv run python dev/nhl_microstat/fit_zone_entry_value.py
"""

from __future__ import annotations

import os

import polars as pl

from sportsdataverse.nhl.nhl_microstat_constants import fit_shot_xg
from sportsdataverse.nhl.nhl_zone_transitions import infer_zone_transitions

ENTRY_WINDOW_S = 8.0
SHOT_TYPES = ("goal", "shot-on-goal", "missed-shot", "blocked-shot")
FIXTURES_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "fixtures", "nhl_microstat")


def _seconds_expr() -> pl.Expr:
    parts = pl.col("time_in_period").str.split(":")
    return parts.list.get(0).cast(pl.Int64) * 60 + parts.list.get(1).cast(pl.Int64)


def main() -> None:
    pbp = pl.read_parquet(os.path.join(FIXTURES_DIR, "pbp_2024_slice.parquet")).with_columns(
        _seconds_expr().alias("_secs")
    )
    xg_model = fit_shot_xg(pbp)
    shots = pbp.filter(pl.col("type_desc_key").is_in(SHOT_TYPES))
    shots = shots.with_columns(xg_model.predict(shots).alias("xg"))

    tr = infer_zone_transitions(pbp).join(
        pbp.select("game_id", "event_idx", "period", "_secs"), on=["game_id", "event_idx"], how="left"
    )

    # xG generated by the entering/exiting team in the window after each transition.
    joined = tr.join(
        shots.select("game_id", "period", "_secs", "xg", pl.col("event_owner_team_id").alias("shot_team")).rename(
            {"_secs": "shot_secs"}
        ),
        on=["game_id", "period"],
        how="left",
    )
    joined = joined.with_columns(
        (
            (pl.col("shot_secs") >= pl.col("_secs"))
            & (pl.col("shot_secs") <= pl.col("_secs") + ENTRY_WINDOW_S)
            & (pl.col("shot_team") == pl.col("team_id"))
        ).alias("_in_window")
    )
    per_tr = joined.group_by(["game_id", "event_idx", "transition_type", "controlled"]).agg(
        (pl.col("xg") * pl.col("_in_window").cast(pl.Float64)).sum().alias("post_xg")
    )

    entries = per_tr.filter(pl.col("transition_type") == "entry")
    ctrl = entries.filter(pl.col("controlled") == True)["post_xg"].mean()  # noqa: E712
    dump = entries.filter(pl.col("controlled") == False)["post_xg"].mean()  # noqa: E712
    exits = per_tr.filter(pl.col("transition_type") == "exit")["post_xg"].mean()
    print(f"zone_entry_value_controlled = {ctrl:.4f}")
    print(f"zone_entry_value_dump       = {dump:.4f}")
    print(f"zone_exit_value             = {exits:.4f}")


if __name__ == "__main__":
    main()
