"""Offline coverage for the AHL / OHL / WHL / QMJHL league wrappers.

The four junior/minor modules are generated by
:func:`sportsdataverse.hockeytech.build_family` from one shared codebase, and were
previously exercised only by gated live tests (0 offline references). These tests
monkeypatch the single ``hockeytech_api`` chokepoint with captured fixtures (the
JSON shape is identical across HockeyTech leagues, so the committed ``pwhl_*``
captures drive every league's parser) and run each league's ``<lg>_*`` wrappers
offline.
"""

from __future__ import annotations

import importlib

import pandas as pd
import polars as pl
import pytest

from tests.conftest import load_fixture

LEAGUES = [
    "ahl",
    "ohl",
    "whl",
    "qmjhl",
    # promoted 2026-07-12 — same shared parser, driven by the pwhl_* fixtures
    "echl",
    "sphl",
    "chl",
    "ushl",
    "bchl",
    "ajhl",
    "sjhl",
    "ojhl",
    "cchl",
    "gojhl",
    "mhl",
    "nojhl",
    "vijhl",
    "kijhl",
    "mjhl",
]

# HockeyTech ``view`` -> captured fixture stem. ``resolve_season_id`` fans out to
# the ``seasons`` view, so every season-aware wrapper needs that mapping too.
_FIXTURE_BY_VIEW = {
    "seasons": "pwhl_seasons",
    "scorebar": "pwhl_schedule_2025",
    "teams": "pwhl_standings_5",  # statviewfeed 'teams' view == standings
    "teamsbyseason": "pwhl_teams_5",
}


@pytest.fixture()
def patched_api(monkeypatch):
    """Serve captured fixtures from the ``hockeytech_api`` chokepoint, keyed by view."""
    from sportsdataverse.hockeytech import _family

    def fake_api(league, feed, view, params=None, **kwargs):
        stem = _FIXTURE_BY_VIEW.get(view)
        return load_fixture("hockeytech", stem) if stem else {}

    monkeypatch.setattr(_family, "hockeytech_api", fake_api)
    return fake_api


@pytest.mark.parametrize("lg", LEAGUES)
def test_league_season_id(patched_api, lg):
    mod = importlib.import_module(f"sportsdataverse.{lg}")
    df = getattr(mod, f"{lg}_season_id")()
    assert isinstance(df, pl.DataFrame)


@pytest.mark.parametrize("lg", LEAGUES)
def test_league_schedule(patched_api, lg):
    mod = importlib.import_module(f"sportsdataverse.{lg}")
    df = getattr(mod, f"{lg}_schedule")()
    assert isinstance(df, pl.DataFrame)
    assert df.height > 0


# season_id=5 is passed explicitly to the season-aware wrappers: resolve_season_id
