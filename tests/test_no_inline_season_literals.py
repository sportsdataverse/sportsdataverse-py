"""Static gate: no new inline season-era literal outside a constants module (quality program 1.2, R-010).

An era boundary written inline (``pl.col("season") > 2013``) is how the CFB kickoff touchback stayed
at 80 through 2013 while the NFL twin moved to a catalogued constant (C-H4, tier C theme T3). This test
walks the AST of every hand-written module under ``sportsdataverse/`` and collects each ordering
comparison (``<``, ``<=``, ``>``, ``>=``) between a season expression (a name, attribute, subscript or
call naming ``season``, e.g. ``pl.col("season")``, ``int(season)``, ``_qbr_season``) and a year literal
(1900-2099). Docstrings and comments are not code and are not scanned; ``==`` / ``!=`` (single-season
data patches) are a different class and are not scanned either.

Exempt: the constants modules (``model_vars.py``, ``*_rules.py``, ``*_constants.py``) and generated
modules (first line ``# GENERATED by tools/codegen/generate.py``: their floors come from the endpoint
YAML). Every other hit must be a row of ``tests/season_literal_allowlist.yaml`` keyed on
``(file, scope, snippet)`` (scope = the enclosing ``Class.method``) with its exact ``count``, an ``id`` (the finding id, or ``C-T3`` -- the era-literal
class -- when the literal has no graded finding of its own), the ``rules/*.yaml`` catalogue id when one
exists, and a reason. The match is exact both ways: a new literal fails, and a literal that moved into
a constant fails until its row is deleted, so the allowlist only shrinks (and never past
``ALLOWLIST_MAX_ROWS``). Plan tasks 3.1 (touchback) and 3.11 (the other CFB/NFL processor literals)
empty it.
"""

from __future__ import annotations

import ast
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "sportsdataverse"
ALLOWLIST = Path(__file__).parent / "season_literal_allowlist.yaml"
#: committed row count: the allowlist may only go down. 75 -> 76 once, for main's #771 (81f9718458), whose
#: `season <= 2013` standalone-try gate reached this branch in the main sync; never raised for topic code.
#: 76 -> 71: main's #778 (2b73fa5a5e) moved five C-H4 kickoff literals into _KICKOFF_2012_RULES_FROM (since
#: plan task 3.1, cfb/model_vars.py TOUCHBACK_YARDLINE_BY_SEASON / KICKOFF_OUT_OF_BOUNDS_SPOT_BY_SEASON).
#: 71 -> 21: plan task 3.11 moved the CFB processor era cuts and the NFL nflfastR era bins into the
#: model_vars constants.
#: 21 -> 22 once, for main's #859 (nbl_rosetta_runtime.start_year `season <= 1998`), reached in the 10-18 sync.
ALLOWLIST_MAX_ROWS = 22
_ORDERING = (ast.Lt, ast.LtE, ast.Gt, ast.GtE)
_GENERATED = "# GENERATED by tools/codegen/generate.py"


def _names_season(node: ast.AST) -> bool:
    if isinstance(node, ast.Name):
        return "season" in node.id.lower()
    if isinstance(node, ast.Attribute):
        return "season" in node.attr.lower()
    if isinstance(node, ast.Subscript):
        return isinstance(node.slice, ast.Constant) and "season" in str(node.slice.value).lower()
    if isinstance(node, ast.Call):
        if any(isinstance(a, ast.Constant) and a.value == "season" for a in node.args):
            return True
        return any(_names_season(a) for a in node.args) or (
            isinstance(node.func, ast.Attribute) and _names_season(node.func.value)
        )
    return False


def _is_year(node: ast.AST) -> bool:
    return isinstance(node, ast.Constant) and type(node.value) is int and 1900 <= node.value < 2100


def _exempt(path: Path, text: str) -> bool:
    name = path.name
    if name == "model_vars.py" or name.endswith(("_rules.py", "_constants.py")):
        return True
    return text.startswith(_GENERATED)


class _Scanner(ast.NodeVisitor):
    """Collect ``(scope, snippet)`` for each season-era comparison; ``scope`` is the enclosing def."""

    def __init__(self, text: str) -> None:
        self.text = text
        self.stack: list[str] = []
        self.hits: list[tuple[str, str]] = []

    def _scoped(self, node: ast.AST) -> None:
        self.stack.append(node.name)  # type: ignore[attr-defined]
        self.generic_visit(node)
        self.stack.pop()

    visit_FunctionDef = visit_AsyncFunctionDef = visit_ClassDef = _scoped

    def visit_Compare(self, node: ast.Compare) -> None:
        operands = [node.left, *node.comparators]
        if (
            any(isinstance(op, _ORDERING) for op in node.ops)
            and any(_is_year(o) for o in operands)
            and any(_names_season(o) for o in operands)
        ):
            snippet = " ".join(ast.get_source_segment(self.text, node).split())
            self.hits.append((".".join(self.stack) or "<module>", snippet))
        self.generic_visit(node)


def season_literals(package: Path = PACKAGE) -> Counter:
    """``Counter`` of ``(file, scope, snippet)`` for every inline season-era comparison in ``package``.

    ``scope`` is the enclosing ``Class.method`` (or ``<module>``): rows are keyed on code, never on a
    line number, and the scope keeps two literals with one spelling but different jobs apart.
    """
    hits: Counter = Counter()
    for path in sorted(package.rglob("*.py")):
        text = path.read_text(encoding="utf-8")
        if _exempt(path, text):
            continue
        scanner = _Scanner(text)
        scanner.visit(ast.parse(text))
        for scope, snippet in scanner.hits:
            hits[(path.relative_to(package.parent).as_posix(), scope, snippet)] += 1
    return hits


def _allowlist() -> list[dict]:
    return yaml.safe_load(ALLOWLIST.read_text(encoding="utf-8"))


def test_allowlist_rows_carry_an_id_and_a_reason_and_only_shrink():
    rows = _allowlist()
    assert all(r.get("id") and r.get("reason") and r.get("file") and r.get("scope") and r.get("snippet") for r in rows)
    assert all(isinstance(r.get("count"), int) and r["count"] >= 1 for r in rows)
    keys = [(r["file"], r["scope"], r["snippet"]) for r in rows]
    assert len(keys) == len(set(keys)), "duplicate allowlist row"
    assert len(rows) <= ALLOWLIST_MAX_ROWS


def test_no_inline_season_literal_outside_the_allowlist():
    found = season_literals()
    allowed = Counter({(r["file"], r["scope"], r["snippet"]): r["count"] for r in _allowlist()})
    new = {k: n for k, n in found.items() if n > allowed.get(k, 0)}
    gone = {k: n for k, n in allowed.items() if found.get(k, 0) < n}
    assert new == {}, f"inline season literal(s) without an allowlist row (use a catalogued constant): {new}"
    assert gone == {}, f"allowlisted literal(s) no longer in the code: delete or lower the row(s): {gone}"


def test_the_scanner_sees_a_planted_literal(tmp_path):
    """Guard the guard: a fresh module with an inline era cut is caught; a docstring mention is not."""
    pkg = tmp_path / "sportsdataverse"
    pkg.mkdir()
    (pkg / "x.py").write_text(
        '"""season > 2013 in prose."""\nimport polars as pl\nE = pl.col("season") > 2013\nF = 2006 < s.season <= 2013\n',
        encoding="utf-8",
    )
    (pkg / "model_vars.py").write_text('E = pl.col("season") > 2013\n', encoding="utf-8")
    found = season_literals(pkg)
    assert sorted(found) == [
        ("sportsdataverse/x.py", "<module>", "2006 < s.season <= 2013"),
        ("sportsdataverse/x.py", "<module>", 'pl.col("season") > 2013'),
    ]
