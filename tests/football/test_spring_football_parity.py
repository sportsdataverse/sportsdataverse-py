"""Phase-1 gate: NFL-parity + spring-football calibration (Task 1.5).

Gate (a) NFL parity: the shared core must reproduce ``enrich_nfl_pbp``
byte-for-byte on an nflverse-shape frame -- ``enrich_spring_football_pbp``
calls ``enrich_nfl_pbp`` directly (see ``spring_football_ep_wp.py``'s
downscope note), so this is a real, not approximate, equality.

Gate (b) league calibration -- **downscope, documented**: the plan specifies
comparing WP against ``espn_{ufl,xfl}_game_probabilities`` (a live oracle
fixture). That endpoint returns HTTP 400
``"Probabilities are not supported for sport: football, league: xfl/ufl"``
for both leagues (confirmed live, see FEASIBILITY.md) -- there is no
oracle to capture. The substitute gate compares the model's per-play ``wp``
against the REALIZED game outcome (Brier) against the naive 0.5-constant
baseline, and checks season-wide (3-game corpus) mean EPA lands within
±0.5 of 0. UFL has zero captured plays (see FEASIBILITY.md), so this
runs on the real captured XFL corpus. Floors are set from the OBSERVED
values below and must never be relaxed to pass -- a regression here means
debug the model/build pipeline, not loosen the assert.
"""

from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import polars as pl
import pytest

from polars.testing import assert_frame_equal

from sportsdataverse._common.metrics import brier_score
from sportsdataverse.football.spring_football_ep_wp import build_spring_football_pbp, enrich_spring_football_pbp
from sportsdataverse.nfl.ep_wp import enrich_nfl_pbp
from tests.conftest import skip_if_no_live

FIXTURE_DIR = Path(__file__).resolve().parents[1] / "fixtures" / "league_ports"

# 3 real, completed XFL 2023 games (events 401517780 / 401517747 / 401517746)
# with full ESPN play-by-play -- see FEASIBILITY.md for capture provenance.
_XFL_FIXTURES = ["xfl_summary.json", "xfl_summary_2.json", "xfl_summary_3.json"]

# One real NFL 2023 game in nflverse shape (model-output columns stripped) --
# regenerated by ``dev/league_ports/capture_spring_football_fixtures.py``.
_NFL_PARITY_FIXTURE = "nfl_parity_2023_game.parquet"

# Observed on the committed corpus above, 2026-07-12 (see this file's module
# docstring for why the oracle is a realized-outcome Brier, not the
# (unsupported, HTTP-400) ESPN probabilities endpoint):
#   model Brier = 0.088645 on N = 442 valid wp rows; mean EPA = -0.3526 on
#   n = 445 non-null EPA rows. The naive baseline is exact (0.5-constant
#   Brier is always 0.25). The Brier ceiling is observed + ~0.02 (mirroring
#   the contract's "oracle + 0.02" margin); the row floors are the observed
#   counts. Re-observation note: the initial capture observed 0.086862 WITH
#   the receive_2h_ko model-input bug (missing nflfastR's qtr<=2 clamp);
#   fixing the input moved the observed Brier to 0.088645 (the buggy H2
#   feature coincidentally flattered this 3-game corpus). That is a bug fix
#   changing the observed value, not a loosened gate -- the ceiling stays
#   observed + ~0.02 = 0.11. NEVER relax any of these to pass -- a
#   regression here means debug the model/build pipeline, not the assert.
# Corpus caveat: N = 442 plays from 3 correlated games is too small for a
# per-decile calibration table -- revisit (add one) at ~10 captured games.
_NAIVE_BRIER = 0.25
_WP_BRIER_CEILING = 0.11
_EPA_MEAN_TOLERANCE = 0.5
_MIN_VALID_WP_ROWS = 442
_MIN_EPA_ROWS = 445


def _load_fixture(name: str) -> dict:
    with open(FIXTURE_DIR / name, encoding="utf-8") as f:
        return json.load(f)


def _game_home_won(summary: dict) -> bool:
    comp = summary["header"]["competitions"][0]
    scores = {c["homeAway"]: int(c["score"]) for c in comp["competitors"]}
    return scores["home"] > scores["away"]


# ---------------------------------------------------------------------------
# Gate (a): NFL parity.
# ---------------------------------------------------------------------------


def test_nfl_parity_shared_core():
    # Reuses a real (XFL) drive->play frame purely as a genuine nflverse-shape
    # frame -- the point of this test is the WIRING identity, not spring-
    # football semantics.
    pbp = build_spring_football_pbp(_load_fixture("xfl_summary.json"), league="xfl")

    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        direct = enrich_nfl_pbp(pbp)
        via_port = enrich_spring_football_pbp(pbp, league="nfl_parity")

    assert direct.columns == via_port.columns
    for col in ("ep", "epa", "wp", "wpa", "cp", "cpoe"):
        a = direct[col].fill_null(-999.0).cast(pl.Float64)
        b = via_port[col].fill_null(-999.0).cast(pl.Float64)
        assert (a - b).abs().max() < 1e-9, col


def test_nfl_parity_on_real_nfl_fixture():
    # Gate (a) proper: same REAL NFL frame in -> byte-identical frame out of
    # both the direct `enrich_nfl_pbp` call and the spring-football port
    # path. Guards against the port path ever mutating the frame (e.g. a
    # future league-constants thread-through) in a way that breaks parity.
    # Note: the xYAC model is download-on-demand (~34MB) -- a cache-cold run
    # touches the network here, but both sides degrade identically when it
    # is unavailable, so the parity assert holds either way.
    nfl = pl.read_parquet(FIXTURE_DIR / _NFL_PARITY_FIXTURE)
    assert nfl.height >= 168  # observed: 168 plays in 2023_01_ARI_WAS
    assert nfl.schema["game_id"] == pl.Utf8

    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        direct = enrich_nfl_pbp(nfl)
        via_port = enrich_spring_football_pbp(nfl, league="nfl_parity")

    assert direct.columns == via_port.columns
    for col in ("ep", "epa", "wp", "wpa", "vegas_wp", "cp", "cpoe"):
        assert col in direct.columns, col
        assert direct[col].drop_nulls().len() > 0, col
    assert_frame_equal(direct, via_port, check_exact=True)  # byte-for-byte


