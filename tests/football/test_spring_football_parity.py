def test_xfl_wp_beats_naive_baseline_on_realized_outcome():
    all_p: list[np.ndarray] = []
    all_y: list[np.ndarray] = []
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        for fname in _XFL_FIXTURES:
            summary = _load_fixture(fname)
            pbp = build_spring_football_pbp(summary, league="xfl")
            out = enrich_spring_football_pbp(pbp, league="xfl")
            home_won = _game_home_won(summary)
            valid = out.filter(pl.col("wp").is_not_null() & pl.col("posteam").is_not_null())
            # Gate (c): the realized-outcome label is a posteam==home_team
            # "join" -- assert dtype agreement on both sides before comparing.
            assert valid.schema["posteam"] == pl.Utf8
            assert valid.schema["home_team"] == pl.Utf8
            y_expr = (
                (pl.col("posteam") == pl.col("home_team")) if home_won else (pl.col("posteam") != pl.col("home_team"))
            )
            all_y.append(valid.select(y_expr.cast(pl.Int8).alias("y"))["y"].to_numpy().astype(float))
            all_p.append(valid["wp"].to_numpy().astype(float))

    y = np.concatenate(all_y)
    p = np.concatenate(all_p)
    # Gate (c): height >= observed N (442 on the committed 3-game corpus).
    assert len(y) >= _MIN_VALID_WP_ROWS

    model_brier = brier_score(y, p)
    naive_brier = brier_score(y, np.full_like(p, 0.5))
    assert abs(naive_brier - _NAIVE_BRIER) < 1e-9  # sanity: naive baseline is exactly 0.25
    assert model_brier <= _WP_BRIER_CEILING, f"model Brier {model_brier:.4f} regressed past the observed ceiling"
    assert model_brier < naive_brier


def test_xfl_season_wide_epa_near_zero():
    all_epa: list[float] = []
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        for fname in _XFL_FIXTURES:
            pbp = build_spring_football_pbp(_load_fixture(fname), league="xfl")
            out = enrich_spring_football_pbp(pbp, league="xfl")
            all_epa.extend(out["epa"].drop_nulls().to_list())

    assert len(all_epa) >= _MIN_EPA_ROWS  # observed n on the committed corpus
    mean_epa = float(np.mean(all_epa))
    assert abs(mean_epa) <= _EPA_MEAN_TOLERANCE, f"season-wide mean EPA {mean_epa:.3f} outside ±{_EPA_MEAN_TOLERANCE}"


