"""Faithful-extraction parity gate for the NHL/MLB native flat modules.

For each *hand-written* family this gate proved the generated module reproduced
every function's exact request (URL + non-None params) for minimal + maximal
calls, excluding a small set of genuinely-irregular functions (``_IRREGULAR``:
3-way branches, mid-segment-embedded record values, conditional ``_csv``/host
shaping) that stay hand-written.

All five families (nhl_api_web, nhl_edge, nhl_stats_rest, nhl_records, mlb_api)
have now been CUT OVER: each was verified by this gate *before* its swap, then
removed from ``_MODULES`` (a generated module has no hand-written twin to diff).
The irregulars were preserved hand-written in ``*_extra.py`` residuals.
``_MODULES`` is empty now and ``test_all_native_families_cut_over`` asserts the
end state; the gate stays in place to guard the next hand-written family added.
"""

import importlib
import importlib.util
import inspect
import tempfile
from pathlib import Path

import pytest
import yaml

from tools.codegen import extract_native as en
from tools.codegen import generate, spec

# ALL native families (nhl_api_web, nhl_edge, nhl_stats_rest, nhl_records, mlb_api)
# have now been CUT OVER to generated modules. Each family's faithfulness was
# locked in by this gate *before* its swap; once a family's hand-written source is
# replaced there is nothing left to diff, so it leaves _MODULES. Each family's
# un-generatable functions are preserved hand-written in a ``*_extra.py`` residual:
#   - nhl_api_web_extra.py : nhl_scoreboard (3-way team/date/now branch)
#   - nhl_records_extra.py : 6 value-embedded / scope-conditional records
#   - mlb_api_extra.py     : 15 conditional-_csv / multi-param / v1.1-host functions
# The gate is retained (empty) so the next hand-written family added is gated again.
_MODULES: list = []
_IRREGULAR: dict = {}  # per-family un-generatable names, gated above before each swap


def test_all_native_families_cut_over():
    """Every native family is now generated, with its residual present + importable."""
    import importlib

    for dotted in (
        "sportsdataverse.nhl.nhl_api_web",
        "sportsdataverse.nhl.nhl_edge",
        "sportsdataverse.nhl.nhl_stats_rest",
        "sportsdataverse.nhl.nhl_records",
        "sportsdataverse.mlb.mlb_api",
    ):
        mod = importlib.import_module(dotted)
        assert "GENERATED by tools/codegen" in (Path(mod.__file__).read_text(encoding="utf-8")[:200]), (
            f"{dotted} is not a generated module"
        )
    for residual in (
        "sportsdataverse.nhl.nhl_api_web_extra",
        "sportsdataverse.nhl.nhl_records_extra",
        "sportsdataverse.mlb.mlb_api_extra",
    ):
        importlib.import_module(residual)  # raises if missing/broken


def _gen_module(dotted, prefix, base, name_pattern, parser_module):
    eps = en.extract_module(dotted, prefix, base, name_pattern)
    doc = {
        "api": dotted.rsplit(".", 1)[-1],
        "host": base,
        "name_pattern": name_pattern,
        "module": dotted.rsplit(".", 1)[-1],
        "parser_module": parser_module,
        "runtime_imports": ["_get", "format_nhl_season"],
        "endpoints": eps,
    }
    # mkdtemp (not the deprecated, race-prone mktemp): one secure temp dir holds
    # both the spec YAML and the rendered module.
    tmpdir = Path(tempfile.mkdtemp())
    yp = tmpdir / "flat_spec.yaml"
    yp.write_text(yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    api = spec.load_flat_api(yp, {})
    src = generate.render_flat_module(api)
    gp = tmpdir / f"{api.module}.py"
    gp.write_text(src, encoding="utf-8")
    s = importlib.util.spec_from_file_location(gp.stem, gp)
    mod = importlib.util.module_from_spec(s)
    s.loader.exec_module(mod)
    return mod, {e["short"] for e in eps}


def _cap(call, sink_owner, sink_name):
    box = {}

    def fake(url=None, params=None, **kw):
        box["url"] = url
        box["params"] = {k: v for k, v in (params or {}).items() if v is not None}
        return None

    orig = getattr(sink_owner, sink_name)
    setattr(sink_owner, sink_name, fake)
    try:
        call()
    finally:
        setattr(sink_owner, sink_name, orig)
    return box


@pytest.mark.parametrize("dotted,prefix,base,name_pattern,parser_module", _MODULES)
def test_native_generated_matches_handwritten(dotted, prefix, base, name_pattern, parser_module):
    import sportsdataverse._codegen_runtime as rt

    hw = importlib.import_module(dotted)
    gen, shorts = _gen_module(dotted, prefix, base, name_pattern, parser_module)

    irregular = _IRREGULAR.get(dotted, set())
    mismatches = []
    for name, hwfn in vars(hw).items():
        if not name.startswith(prefix) or not callable(hwfn) or name.startswith("_"):
            continue
        if name in irregular:
            continue
        gfn = getattr(gen, name, None)
        if gfn is None:
            mismatches.append(f"{name}: missing in generated")
            continue
        sigp = [
            p for p in inspect.signature(hwfn).parameters.values() if p.name != "kwargs" and p.kind != p.VAR_KEYWORD
        ]
        for maximal in (False, True):
            args = {
                p.name: (en._val(p.name) if (maximal or p.default is inspect.Parameter.empty) else p.default)
                for p in sigp
                if (maximal or p.default is inspect.Parameter.empty)
            }
            try:
                want = _cap(lambda: hwfn(**args), hw, "download")
                got = _cap(lambda: gfn(**args), rt, "download")
            except Exception as e:  # noqa: BLE001
                mismatches.append(f"{name} (max={maximal}) raised: {e}")
                continue
            if got.get("url") != want.get("url"):
                mismatches.append(f"{name} (max={maximal}) URL:\n   hw:  {want.get('url')}\n   gen: {got.get('url')}")
            elif got.get("params") != want.get("params"):
                mismatches.append(
                    f"{name} (max={maximal}) PARAMS: hw={want.get('params')} gen={got.get('params')}",
                )
    assert not mismatches, f"{len(mismatches)} parity mismatch(es) in {dotted}:\n" + "\n".join(mismatches[:30])
