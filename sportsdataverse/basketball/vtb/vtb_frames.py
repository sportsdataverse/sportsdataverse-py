"""Shared row and frame helpers for the VTB parsers (``vtb_league_parsers`` and ``vtb_infobasket_parsers``).

Not public API: the ``parse_vtb_*`` functions are. Everything here follows the package parser contract: polars by default,
pandas with ``return_as_pandas=True``, snake_case columns (``dl_utils.underscore``), and a zero-row frame typed from the
documented returns schema (:data:`DTYPES`, generated into ``vtb_dtypes`` by ``tools/codegen/gen_vtb.py``) for an empty or
malformed body.

**Wire conversions** (applied to every value by :func:`flat`):

* ``/Date(ms)/`` (.NET, milliseconds since the Unix epoch) -> an ISO 8601 string in **Moscow time with its offset**
  (``2025-09-28T14:00:00+03:00``); the year-1 value ``/Date(-62135596800000)/`` is Infobasket's "unset" and becomes null.
* ``DD.MM.YYYY`` -> ``YYYY-MM-DD``.
* ``''`` in an id, rank or number column (``LiveID``, the roster's ``Rank``, which is blank in every sample) -> null.
* Percentages and averages arrive as strings with a comma decimal (``'68,2'``, ``'80,3%'``, ``''`` when there were no
  attempts): :func:`decimals` turns the ``*_percent`` and ``avg_*`` columns into ``Float64``.
* ``made/attempted`` strings (``'15/22'``) and the broken paint stats are dropped: the integer ``goal*`` / ``shot*``
  columns carry the same numbers.
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, Iterable, List, Mapping, Optional, Sequence, Union

import pandas as pd
import polars as pl

from sportsdataverse._codegen_runtime import _cast_ids_int64
from sportsdataverse.dl_utils import underscore

try:  # generated by tools/codegen/gen_vtb.py
    from sportsdataverse.basketball.vtb.vtb_dtypes import DTYPES
except ImportError:  # pragma: no cover -- first run of the generator
    DTYPES = {}

Frame = Union[pl.DataFrame, pd.DataFrame]

#: Where the runtimes stamp the request.
REQUEST_KEY = "_request"
MSK = timezone(timedelta(hours=3))
_NET_DATE = re.compile(r"^/Date\((-?\d+)\)/$")
_DMY = re.compile(r"^(\d\d)\.(\d\d)\.(\d{4})$")
_UNSET_MS = -62135596800000  # year 1: Infobasket's "no date"
_ID_COL = re.compile(r"(^|_)id$")
_BLANK_NULL = re.compile(r"(^|_)(id|rank|number)$")
_DTYPE_CODES = {"i": pl.Int64, "f": pl.Float64, "b": pl.Boolean, "s": pl.String}

#: Wire keys never output: platform bookkeeping, system/operator fields, empty relation lists and personal data.
JUNK = frozenset(
    {
        "SysStatus", "SysLastChanged", "SysClientLastChanged", "SysUser", "SysMyUser",
        "PersonGUID", "TeamGUID", "GameGUID", "RegionGUID", "ArenaGUID",
        "PersonContacts", "PersonPhotoes", "PersonOldNames", "GameStartlists", "Referees", "Officials",
        "LicenceNumber", "PersonEmail", "PersonPhone", "Email", "Phone",
        "Age", "PersonBirthday", "PersonBirthYear",
        "CompTeams", "Team", "Person", "CompTeam",
    }
)  # fmt: skip
#: The made/attempted strings and the broken paint statistics (see the module docstring).
_DROP_COL = re.compile(r"(^|_)(shots[123]|shots23|avg_shots\d+)$|(^|_)paint_")
_RENAME = {
    "comp_i_dparent": "parent_comp_id",
    "team1id": "team1_id",
    "team2id": "team2_id",
    "team_aid": "team_a_id",
    "team_bid": "team_b_id",
    "capitan": "is_captain",
    "person_birth": "birth_date",
    "nationality_id": "nationality_code",  # an ISO code ('BY'), not a numeric id
    "country_id": "country_code",
}
#: Counting statistics: Infobasket sends null instead of 0 (``vtb-returns.md`` divergence notes).
COUNTS = frozenset(
    {
        "points", "shot1", "goal1", "shot2", "goal2", "shot3", "goal3", "shot23", "goal23", "assist", "blocks",
        "def_rebound", "off_rebound", "rebound", "steal", "turnover", "foul", "opponent_foul",
        "team_def_rebound", "team_off_rebound", "team_rebound", "team_steal", "team_turnover",
        "foul_b", "foul_c", "foul_d",
    }
)  # fmt: skip


# --- values and rows --------------------------------------------------------------------------------------------------


def obj(value: Any) -> Mapping[str, Any]:
    """``value`` if it is a dict, else an empty dict."""
    return value if isinstance(value, dict) else {}


def rows(value: Any) -> List[Mapping[str, Any]]:
    """The dict members of ``value`` if it is a list, else ``[]``."""
    return [v for v in value if isinstance(v, dict)] if isinstance(value, list) else []


def int_or_none(value: Any) -> Optional[int]:
    """``value`` if it is an int (not a bool), else ``None``."""
    return value if isinstance(value, int) and not isinstance(value, bool) else None


def request(raw: Any) -> Mapping[str, Any]:
    """The request the runtime stamped under ``_request`` ({} for a bare body)."""
    return obj(obj(raw).get(REQUEST_KEY))


def items(raw: Any) -> List[Mapping[str, Any]]:
    """Rows of a list route: ``items`` of the stamped body, or a bare list."""
    return rows(raw) if isinstance(raw, list) else rows(obj(raw).get("items"))


def conv(value: Any) -> Any:
    """Convert one wire value (see the module docstring); anything else passes through."""
    if not isinstance(value, str):
        return value
    m = _NET_DATE.match(value)
    if m:
        ms = int(m.group(1))
        if ms <= _UNSET_MS:
            return None
        return datetime.fromtimestamp(ms / 1000, MSK).isoformat(timespec="seconds")
    m = _DMY.match(value)
    return f"{m.group(3)}-{m.group(2)}-{m.group(1)}" if m else value


def flat(
    node: Mapping[str, Any],
    prefix: str = "",
    skip: Iterable[str] = (),
    *,
    parent: str = "",
    birth: bool = False,
) -> Dict[str, Any]:
    """One flat row: nested objects as ``<parent>_<child>``, non-empty lists as JSON strings, junk left out.

    Args:
        node: the wire object.
        prefix: prepended to every column name.
        skip: wire keys to leave out, bare (``"Players"``) or qualified by their parent (``"TeamName.TeamID"``).
        parent: the wire key of ``node`` inside its parent (for qualified ``skip`` entries).
        birth: keep ``PersonBirth`` (a player's public birth date). Coaches', referees' and officials' birth data is never
            output, whatever the body holds.

    Returns:
        ``{column: value}`` with the wire conversions applied.
    """
    skip = skip if isinstance(skip, (set, frozenset)) else frozenset(skip)
    out: Dict[str, Any] = {}
    for key, value in node.items():
        if key == REQUEST_KEY or key in JUNK or key in skip or f"{parent}.{key}" in skip:
            continue
        if key == "PersonBirth" and not birth:
            continue
        name = prefix + underscore(str(key))
        if isinstance(value, list):
            if value:
                out[name] = json.dumps(value, ensure_ascii=False)
        elif isinstance(value, dict):
            out.update(flat(value, name + "_", skip, parent=str(key), birth=birth))
        elif value == "" and _BLANK_NULL.search(name):
            out[name] = None
        else:
            out[name] = conv(value)
    return out


def tidy(row: Dict[str, Any], *, counts: bool = False) -> Dict[str, Any]:
    """Rename the awkward columns, drop the unusable ones, parse the comma decimals and (``counts``) null counts to 0."""
    out: Dict[str, Any] = {}
    for name, value in row.items():
        name = _RENAME.get(name, name)
        name = re.sub(r"(^|_)team1id$", r"\1team1_id", name)
        name = re.sub(r"(^|_)team2id$", r"\1team2_id", name)
        if _DROP_COL.search(name):
            continue
        if name.endswith("_percent") or (name.startswith("avg_") and name != "avg_played_time"):
            value = decimal(value)
        elif counts and name in COUNTS and value is None:
            value = 0
        out[name] = value
    if "is_captain" in out and isinstance(out["is_captain"], int):
        out["is_captain"] = bool(out["is_captain"])
    return out


def decimal(value: Any) -> Optional[float]:
    """A comma-decimal string (``'68,2'``, ``'80,3%'``, ``''``) as a float; numbers pass through; anything else is null."""
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str):
        text = value.strip().rstrip("%").replace(",", ".")
        try:
            return float(text)
        except ValueError:
            return None
    return None


# --- frames -----------------------------------------------------------------------------------------------------------


def dtype_for(col: str, schema: Optional[Mapping[str, str]] = None) -> Any:
    """A column's dtype without a value to go by: the returns schema, else Int64 for an id, else String."""
    code = (schema or {}).get(col)
    if code:
        return _DTYPE_CODES[code]
    return pl.Int64 if _ID_COL.search(col) else pl.String


def frame(data: Iterable[Mapping[str, Any]]) -> pl.DataFrame:
    """Rows -> a frame with every id column ``Int64``; an empty or malformed input -> an empty frame."""
    data = [r for r in data if r]
    if not data:
        return pl.DataFrame()
    try:
        df = pl.from_dicts(data, infer_schema_length=None, strict=False)
    except Exception:  # noqa: BLE001 -- a malformed body parses to nothing, never raises
        return pl.DataFrame()
    df = _cast_ids_int64(df, [c for c in df.columns if _ID_COL.search(c)])
    casts = [pl.col(c).cast(dtype_for(c)) for c, d in df.schema.items() if d == pl.Null]
    return df.with_columns(casts) if casts else df


def finish(df: pl.DataFrame, columns: Optional[Sequence[str]], return_as_pandas: bool, parser: str) -> Frame:
    """Apply the returns-schema dtypes and the documented columns.

    An all-null column (and a whole-number rate) takes the schema dtype; an empty frame keeps the documented columns and a
    column the body lacked is added as nulls, all typed like a populated frame, so frames stack.
    """
    schema = DTYPES.get(parser, {})
    if schema and df.width:
        casts = []
        for col, dtype in df.schema.items():
            want = dtype_for(col, schema) if col in schema else dtype
            if dtype != want and (df[col].null_count() == df.height or (want == pl.Float64 and dtype.is_numeric())):
                casts.append(pl.col(col).cast(want))
        df = df.with_columns(casts) if casts else df
    columns = list(columns) if columns else list(schema)
    if columns:
        if df.width == 0:
            df = pl.DataFrame(schema={c: dtype_for(c, schema) for c in columns})
        else:
            missing = [pl.lit(None, dtype=dtype_for(c, schema)).alias(c) for c in columns if c not in df.columns]
            if missing:
                df = df.with_columns(missing)
            df = df.select([*columns, *[c for c in df.columns if c not in columns]])
    return df.to_pandas() if return_as_pandas else df
