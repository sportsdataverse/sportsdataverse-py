"""Parsers for the CBA (Chinese Basketball Association) wrappers over data-server.cbaleague.com.

``cba_runtime._get`` returns the DECRYPTED body, stamped with ``_request`` (``{"schedule_id": ...}`` for the game
routes that answer an object). Every parser takes that body (``return_parsed=False``) and returns a polars frame
(pandas with ``return_as_pandas=True``) with snake_case columns (``dl_utils.underscore``) typed from the full bodies
(``cba_dtypes.DTYPES``, generated by ``tools/codegen/gen_cba.py``). An empty or unrecognised body gives a zero-row
frame with the documented columns, so empty frames stack onto populated ones.

**Row rule** (one entry of :data:`ROUTES` per parser): a list body is the rows; ``records`` is the page of a paged
route; a two-sided body (``homeCounts`` / ``visitingCounts``...) gives one block per side with a ``side`` column
(``home`` / ``away``); a dict body is one row. Nested lists (the play-by-play ``player_cn_names``) become JSON text.
``createdBy`` / ``lastModifiedBy`` (CMS operator ids, one holds a phone number) are dropped.

**Ids** (one dtype per id, Int64; never a float rendered as text):

* ``schedule_id``: CBA games, ONE global 9-digit sequence ``100xxxxxx`` across seasons and match types.
* ``team_id``: clubs, stable across seasons and sponsor renames (the NAME changes with the sponsor).
* ``player_id``: persons, stable across seasons and clubs (a string on the wire in ``best_stats``; cast here).
* ``match_type_id``: 1 regular season, 2 playoffs, 3 preseason, 4 all-star, 9 relegation play-off.
* roster ``id``: a (player, team, season) registration, a 19-digit integer.

**Seasons.** The wire ``season`` is the START year (2025 = 2025-26); the sdv END year is ``season + 1``. The
season columns keep the wire value.

**Duplicate rows.** ``advance-count`` and ``schedule-other-data`` repeat player rows in some games (2025-26 game
100105799: 26 rows for 12 players); the repeats are not always copies. Those parsers keep the FIRST row per
``player_id``. ``player_box`` has one row per player plus a team row (null ``player_id``).
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Optional, Sequence, Tuple, Union

import pandas as pd
import polars as pl

from sportsdataverse.dl_utils import underscore
from sportsdataverse.errors import _data_only

try:  # generated by tools/codegen/gen_cba.py
    from sportsdataverse.basketball.cba.cba_dtypes import DTYPES
except ImportError:  # pragma: no cover -- first run of the generator
    DTYPES = {}

Frame = Union[pl.DataFrame, pd.DataFrame]
REQUEST_KEY = "_request"
_CODES = {"i": pl.Int64, "f": pl.Float64, "b": pl.Boolean, "s": pl.String}
#: Wire keys never output (operator ids, one holds a mobile phone number).
JUNK = frozenset({"createdBy", "lastModifiedBy"})
_SIDES_HOME_AWAY = ("home", "away")

#: short -> (row rule, keys). Rules: ``list``, ``records``, ``one``, ``sides`` (list per side), ``sideobj`` (object per
#: side), ``periods``. ``dedupe`` shorts keep the first row per ``playerId``.
ROUTES: Dict[str, Tuple[str, Tuple[str, ...]]] = {
    "seasons": ("list", ()),
    "match_types": ("list", ()),
    "team_options": ("list", ()),
    "teams": ("list", ()),
    "schedule_month": ("list", ()),
    "schedule_day": ("list", ()),
    "game_info": ("one", ()),
    "player_box": ("sides", ("homeCounts", "visitingCounts")),
    "period_scores": ("periods", ("home", "visiting")),
    "game_team_shots": ("list", ()),
    "player_advanced": ("sides", ("homes", "visitings")),
    "player_extras": ("sides", ("homePlayers", "visitingPlayers")),
    "game_team_four": ("list", ()),
    "best_player": ("sideobj", ("hostBestPlayer", "guestBestPlayer")),
    "best_stats": ("sides", ("hostTeamBestData", "guestTeamBestData")),
    "rosters": ("sides", ("hostPlayers", "guestPlayers")),
    "report_status": ("one", ()),
    "pbp": ("records", ()),
    "team_counts": ("list", ()),
    "team_basic": ("list", ()),
    "team_four": ("list", ()),
    "team_overview": ("records", ()),
    "team_shots": ("records", ()),
    "player_base": ("records", ()),
    "player_offensive": ("records", ()),
    "player_defensive": ("records", ()),
    "player_shots": ("records", ()),
}
_DEDUPE = frozenset({"player_advanced", "player_extras"})
_PERIODS = ("oneScore", "twoScore", "threeScore", "fourScore", "fiveScore", "sixScore", "sevenScore")


def _cast(value: Any, code: str) -> Any:
    """``value`` as the dtype ``code`` (``i`` / ``f`` / ``b`` / ``s``); ``None`` when it does not convert."""
    if value is None:
        return None
    if code == "s":
        if isinstance(value, (list, dict)):
            return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        return str(value)
    if code == "b":
        return value if isinstance(value, bool) else None
    if isinstance(value, bool):
        return None
    try:
        if code == "i":
            if isinstance(value, float):
                return int(value) if value == int(value) else None
            return int(value)
        return float(value)
    except (TypeError, ValueError):
        return None


def _flat(row: Dict[str, Any]) -> Dict[str, Any]:
    return {underscore(k): v for k, v in row.items() if k not in JUNK and k != REQUEST_KEY}


def _rows(short: str, raw: Any) -> List[Dict[str, Any]]:
    """The flat row dicts of ``raw`` under the route's row rule (``[]`` for an unrecognised body)."""
    rule, keys = ROUTES[short]
    req = raw.get(REQUEST_KEY) if isinstance(raw, dict) else None
    sid = req.get("schedule_id") if isinstance(req, dict) else None
    extra = {"schedule_id": sid} if isinstance(raw, dict) and "schedule_id" in DTYPES.get(short, {}) else {}
    out: List[Dict[str, Any]] = []
    if rule == "list":
        out = [_flat(r) for r in raw if isinstance(r, dict)] if isinstance(raw, list) else []
    elif rule == "records":
        recs = raw.get("records") if isinstance(raw, dict) else None
        out = [{**extra, **_flat(r)} for r in recs if isinstance(r, dict)] if isinstance(recs, list) else []
    elif rule == "one":
        out = [_flat(raw)] if isinstance(raw, dict) and set(_flat(raw)) & set(DTYPES.get(short, {})) else []
        out = [{**extra, **r} for r in out]
    elif rule in ("sides", "sideobj") and isinstance(raw, dict):
        for side, key in zip(_SIDES_HOME_AWAY, keys):
            block = raw.get(key)
            block = [block] if isinstance(block, dict) else block
            seen = set()
            for r in block if isinstance(block, list) else []:
                if not isinstance(r, dict):
                    continue
                if short in _DEDUPE:
                    if r.get("playerId") is None or r["playerId"] in seen:
                        continue
                    seen.add(r["playerId"])
                out.append({**extra, "side": side, **_flat(r)})
    elif rule == "periods" and isinstance(raw, dict):
        for side, key in zip(_SIDES_HOME_AWAY, keys):
            block = raw.get(key)
            for n, name in enumerate(_PERIODS, 1):
                if isinstance(block, dict) and block.get(name) is not None:
                    out.append({**extra, "side": side, "period": n, "points": block[name]})
    return out


def _frame(short: str, raw: Any, as_pandas: bool, columns: Optional[Sequence[str]]) -> Frame:
    rows = _rows(short, raw)
    spec = dict(DTYPES.get(short, {}))
    for c in columns or ():
        spec.setdefault(c, "s")
    for r in rows:  # a wire column the full bodies never showed
        for c in r:
            spec.setdefault(c, "s")
    data = {c: [_cast(r.get(c), code) for r in rows] for c, code in spec.items()}
    df = pl.DataFrame(data, schema={c: _CODES[code] for c, code in spec.items()}, strict=False)
    return df.to_pandas() if as_pandas else df


