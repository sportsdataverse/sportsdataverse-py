"""Quality scoreboard for sdv-py: measure the hand-written code, snapshot it, ratchet it.

Run from the sdv-py repository root, inside its uv environment (Python 3.11+):

    uv run --frozen python <this file> --write snapshot.json [--coverage-json coverage.json]
    uv run --frozen python <this file> --compare baseline.json [--coverage-json coverage.json]

``--write`` records every metric. ``--compare`` prints a before/after table and exits 1 when
any metric is worse than the baseline; when nothing got worse its last line is exactly
``SCOREBOARD OK: no metric regressed`` (the success marker the phase gates match on).

Coverage is read from an existing ``pytest --cov --cov-report=json:<path>`` file rather than
re-running the suite (the full suite takes ~13 minutes). Without ``--coverage-json`` the
coverage metrics are skipped, never treated as zero.

Generated code is excluded everywhere: ``*_espn_ext.py``, ``sportsdataverse/parsed/``, and any
module whose first ten lines carry the codegen marker. Edit those through tools/codegen instead.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import subprocess
import sys
import tomllib
from datetime import datetime, timezone
from pathlib import Path

PACKAGE = "sportsdataverse"
CODEGEN_MARKER = "GENERATED by tools/codegen/generate.py -- DO NOT EDIT"

# Ruff rule families, measured on hand-written code only. Key = snapshot metric name.
LINT_FAMILIES = {
    "UP": ("lint_outdated_syntax", "Outdated syntax a newer Python spells shorter (ruff UP)"),
    "C4": ("lint_comprehensions", "Loops and calls that should be comprehensions (ruff C4)"),
    "SIM": ("lint_simplifiable_code", "Code with a simpler equivalent (ruff SIM)"),
    "B": ("lint_likely_bugs", "Likely-bug patterns such as mutable defaults (ruff B)"),
    "RET": ("lint_return_style", "Redundant or inconsistent returns (ruff RET)"),
    "PIE": ("lint_unnecessary_code", "Unnecessary statements and calls (ruff PIE)"),
    "PERF": ("lint_performance_patterns", "Slow loop patterns (ruff PERF)"),
    "RUF": ("lint_ruff_specific", "Ruff-specific correctness and style rules (ruff RUF, without RUF100)"),
    # The two noqa buckets are split out of ruff RUF100 by its message, not by rule code.
    "NOQA_STALE": ("lint_stale_noqa_comments", "noqa comments naming an enabled rule that never fires (ruff RUF100)"),
    "NOQA_NOT_RUN": (
        "lint_noqa_for_rules_not_run",
        "noqa comments naming a rule the project does not run (ruff RUF100)",
    ),
    "ARG": ("lint_unused_arguments", "Function arguments never used (ruff ARG)"),
    "F841": ("lint_unused_variables", "Local variables assigned but never used (ruff F841)"),
    "C901": ("lint_too_complex_functions", "Functions over complexity 10 (ruff C901)"),
    "PLR0912": ("lint_too_many_branches", "Functions with over 12 branches (ruff PLR0912)"),
    "PLR0915": ("lint_too_many_statements", "Functions with over 50 statements (ruff PLR0915)"),
}
EXACT_CODES = {"F841", "C901", "PLR0912", "PLR0915"}
NOQA_BUCKETS = ("NOQA_STALE", "NOQA_NOT_RUN")

# Allowed noise before a "higher is better" percentage counts as a regression.
TOLERANCE = {"coverage_handwritten_percent": 0.1}

HOTSPOTS = [  # the largest hand-written modules; their coverage is tracked one by one
    "sportsdataverse/cfb/cfb_pbp.py",
    "sportsdataverse/nfl/nfl_pbp.py",
    "sportsdataverse/nfl/ep_wp.py",
    "sportsdataverse/nfl/nfl_loaders.py",
    "sportsdataverse/nfl/nfl_stats.py",
    "sportsdataverse/_common_espn_parsers.py",
    "sportsdataverse/mbb/mbb_rapm.py",
]


def is_generated(path: Path, rel: str) -> bool:
    if rel.endswith("_espn_ext.py") or rel.startswith(f"{PACKAGE}/parsed/"):
        return True
    with path.open(encoding="utf-8", errors="replace") as fh:
        head = "".join(next(fh, "") for _ in range(10))
    return CODEGEN_MARKER in head


def handwritten_files(root: Path) -> dict[str, Path]:
    files = {}
    for path in sorted((root / PACKAGE).rglob("*.py")):
        rel = path.relative_to(root).as_posix()
        if not is_generated(path, rel):
            files[rel] = path
    return files


def lint_family(code: str) -> str | None:
    if code in EXACT_CODES:
        return code
    if code.startswith("C4"):
        return "C4"
    prefix = re.match(r"[A-Z]+", code)
    family = prefix.group(0) if prefix else None
    return family if family in LINT_FAMILIES else None


def ruff_findings(root: Path, *args: str) -> list[tuple[str, str, str]]:
    """(repo-relative path, rule code, message) per finding. --no-fix: the repo config sets fix = true."""
    cmd = [sys.executable, "-m", "ruff", "check", PACKAGE, "--no-fix", "--exit-zero", "--output-format", "json", *args]
    out = subprocess.run(cmd, cwd=root, capture_output=True, text=True, encoding="utf-8", check=True).stdout
    return [
        (Path(item["filename"]).resolve().relative_to(root.resolve()).as_posix(), item["code"] or "", item["message"])
        for item in json.loads(out or "[]")
    ]


def noqa_bucket(message: str) -> str:
    """RUF100 says why a noqa is unused; only "non-enabled" alone means the rule is simply not run."""
    reasons = set(re.findall(r"(unused|non-enabled|unknown|disabled|duplicated):", message))
    return "NOQA_NOT_RUN" if reasons == {"non-enabled"} else "NOQA_STALE"


def measure_lint(root: Path, files: dict[str, Path]) -> tuple[dict[str, int], dict[str, dict[str, int]]]:
    # The families run clears the config's ignore list (it hides F841), so it must not judge noqa
    # comments: with the ignore list cleared, every E712 suppression looks unused. The CLI --ignore
    # (not a --config override, which the CLI --select would outrank) keeps RUF100 out of it, and
    # The noqa comments are judged in a second run under the project's real rule set.
    families = [c for c in LINT_FAMILIES if c not in NOQA_BUCKETS]
    findings = [
        (rel, lint_family(code))
        for rel, code, _ in ruff_findings(
            root, "--config", "lint.ignore = []", "--select", ",".join(families), "--ignore", "RUF100"
        )
    ]
    findings += [
        (rel, noqa_bucket(msg))
        for rel, code, msg in ruff_findings(root, "--extend-select", "RUF100")
        if code == "RUF100"
    ]
    totals = dict.fromkeys(LINT_FAMILIES, 0)
    by_file: dict[str, dict[str, int]] = {}
    for rel, family in findings:
        if rel not in files or family is None:
            continue
        totals[family] += 1
        by_file.setdefault(rel, {}).setdefault(family, 0)
        by_file[rel][family] += 1
    return totals, by_file


def measure_size(files: dict[str, Path]) -> dict:
    functions, classes, modules, unparsable = [], [], [], []
    total_lines = 0
    for rel, path in files.items():
        source = path.read_text(encoding="utf-8", errors="replace")
        n_lines = source.count("\n") + 1
        total_lines += n_lines
        modules.append((n_lines, rel))
        try:
            tree = ast.parse(source)
        except SyntaxError:
            unparsable.append(rel)
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                span = node.end_lineno - node.lineno + 1
                bucket = classes if isinstance(node, ast.ClassDef) else functions
                bucket.append((span, f"{rel}:{node.lineno} {node.name}"))
    functions.sort(reverse=True)
    classes.sort(reverse=True)
    modules.sort(reverse=True)
    return {
        "total_lines": total_lines,
        "functions_over_100": sum(1 for s, _ in functions if s > 100),
        "functions_over_200": sum(1 for s, _ in functions if s > 200),
        "classes_over_800": sum(1 for s, _ in classes if s > 800),
        "modules_over_1500": sum(1 for s, _ in modules if s > 1500),
        "longest_functions": [f"{s} lines  {name}" for s, name in functions[:20]],
        "largest_classes": [f"{s} lines  {name}" for s, name in classes[:10]],
        "largest_modules": [f"{s} lines  {name}" for s, name in modules[:20]],
        "unparsable": unparsable,
    }


def measure_coverage(coverage_json: Path, files: dict[str, Path]) -> dict:
    data = json.loads(coverage_json.read_text(encoding="utf-8"))
    per_file = {k.replace("\\", "/"): v["summary"] for k, v in data["files"].items()}
    covered = statements = 0
    never_run = []
    for rel in files:
        summary = per_file.get(rel)
        if summary is None or summary["num_statements"] == 0:
            continue
        covered += summary["covered_lines"]
        statements += summary["num_statements"]
        if summary["covered_lines"] == 0:
            never_run.append(rel)
    hotspots = {}
    for rel in HOTSPOTS:
        summary = per_file.get(rel)
        if summary and summary["num_statements"]:
            hotspots[rel] = round(100 * summary["covered_lines"] / summary["num_statements"], 2)
    return {
        "percent": round(100 * covered / statements, 2) if statements else 0.0,
        "never_run": sorted(never_run),
        "hotspots": hotspots,
    }


def mypy_checked_files(root: Path) -> int:
    config = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    return len(config.get("tool", {}).get("mypy", {}).get("files", []))


def metric(value: float, better: str, label: str) -> dict:
    return {"value": value, "better": better, "label": label}


def snapshot(root: Path, coverage_json: Path | None) -> dict:
    files = handwritten_files(root)
    lint, lint_by_file = measure_lint(root, files)
    size = measure_size(files)
    metrics = {
        "handwritten_files": metric(len(files), "info", "Hand-written modules"),
        "handwritten_lines": metric(size["total_lines"], "info", "Hand-written lines"),
        "functions_over_100_lines": metric(size["functions_over_100"], "lower", "Functions over 100 lines"),
        "functions_over_200_lines": metric(size["functions_over_200"], "lower", "Functions over 200 lines"),
        "classes_over_800_lines": metric(size["classes_over_800"], "lower", "Classes over 800 lines"),
        "modules_over_1500_lines": metric(size["modules_over_1500"], "lower", "Modules over 1,500 lines"),
        "mypy_checked_files": metric(mypy_checked_files(root), "higher", "Files in the mypy strict list"),
    }
    for code, (name, label) in LINT_FAMILIES.items():
        metrics[name] = metric(lint[code], "lower", label)
    details = {
        "longest_functions": size["longest_functions"],
        "largest_classes": size["largest_classes"],
        "largest_modules": size["largest_modules"],
        "unparsable_files": size["unparsable"],
        "most_lint_findings_by_file": sorted(
            ({"file": f, "total": sum(c.values()), **c} for f, c in lint_by_file.items()),
            key=lambda row: -row["total"],
        )[:25],
    }
    if coverage_json is not None:
        cov = measure_coverage(coverage_json, files)
        metrics["coverage_handwritten_percent"] = metric(
            cov["percent"], "higher", "Line coverage of hand-written code (%)"
        )
        metrics["modules_never_run_by_tests"] = metric(
            len(cov["never_run"]), "lower", "Hand-written modules no test executes"
        )
        for rel, pct in cov["hotspots"].items():
            metrics[f"coverage_{Path(rel).stem}_percent"] = metric(pct, "higher", f"Line coverage of {rel} (%)")
        details["modules_never_run_by_tests"] = cov["never_run"]
    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=root, capture_output=True, text=True
    ).stdout.strip()
    return {
        "commit": commit,
        "measured_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "metrics": metrics,
        "details": details,
    }


def compare(baseline: dict, current: dict) -> list[str]:
    print(f"Baseline {baseline['commit']} ({baseline['measured_at']})  vs  now {current['commit']}\n")
    print("| Metric | Baseline | Now | Change | Status |\n|---|---:|---:|---:|---|")
    regressions = []
    for name, now in current["metrics"].items():
        before = baseline["metrics"].get(name)
        if before is None:
            print(f"| {now['label']} | (new) | {now['value']} | | new |")
            continue
        delta = round(now["value"] - before["value"], 2)
        allowed = TOLERANCE.get(name, 0)
        if now["better"] == "info" or delta == 0:
            status = "info" if now["better"] == "info" else "same"
        elif (delta < 0) == (now["better"] == "lower"):
            status = "better"
        elif abs(delta) <= allowed:
            status = "same (within noise)"
        else:
            status = "WORSE"
            regressions.append(f"{now['label']}: {before['value']} -> {now['value']}")
        print(f"| {now['label']} | {before['value']} | {now['value']} | {delta:+} | {status} |")
    for name in baseline["metrics"].keys() - current["metrics"].keys():
        print(
            f"| {baseline['metrics'][name]['label']} | {baseline['metrics'][name]['value']} | (not measured) | | skipped |"
        )
    return regressions


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", type=Path, help="write a snapshot JSON to this path")
    action.add_argument("--compare", type=Path, help="compare against this baseline snapshot")
    parser.add_argument("--coverage-json", type=Path, help="pytest-cov JSON report to read coverage from")
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="sdv-py repository root (default: cwd)")
    parser.add_argument(
        "--current", type=Path, help="with --compare: compare this saved snapshot instead of measuring the repo"
    )
    args = parser.parse_args()

    if args.current:
        if not args.compare:
            parser.error("--current only works with --compare")
        current = json.loads(args.current.read_text(encoding="utf-8"))
    else:
        root = args.root.resolve()
        if not (root / PACKAGE).is_dir():
            parser.error(f"{root} is not the sdv-py repository root (no {PACKAGE}/ directory)")
        current = snapshot(root, args.coverage_json)

    if args.write:
        args.write.write_text(json.dumps(current, indent=2) + "\n", encoding="utf-8", newline="\n")
        for m in current["metrics"].values():
            print(f"{m['label']}: {m['value']}")
        print(f"\nSnapshot written to {args.write}")
        return 0

    regressions = compare(json.loads(args.compare.read_text(encoding="utf-8")), current)
    if regressions:
        print("\nSCOREBOARD FAILED: these metrics got worse:\n  " + "\n  ".join(regressions))
        return 1
    print("\nSCOREBOARD OK: no metric regressed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
