#!/usr/bin/env python3
"""commit-msg hook: enforce Conventional Commits + forbid AI co-author trailers.

CLAUDE.md mandates both ("Use Conventional Commits" and "Never include AI agents
as co-authors"), but nothing enforced them. Wired as a pre-commit ``commit-msg``
stage hook (see ``.pre-commit-config.yaml``). Reads the commit message file
(``argv[1]``), validates the subject against ``<type>(<scope>)!: <subject>``
(scope and ``!`` optional), and rejects any ``Co-Authored-By:`` trailer naming an
AI tool. A non-zero exit blocks the commit.
"""

from __future__ import annotations

import re
import sys

TYPES = "feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert"
SUBJECT = re.compile(rf"^({TYPES})(\([^)]+\))?!?: .+")
_VENDORS = (
    r"claude|copilot|cursor|gpt-?[0-9]*|chatgpt|gemini|anthropic|openai|bard"
    r"|codeium|tabnine|devin|aider|windsurf|cody"
)
# Two shapes are needed: a trailer-only check lets the marketing footer through.
AI = re.compile(rf"co-?authored[-\s]?(by|with)\s*:.*\b({_VENDORS})\b", re.I)
AI_FOOTER = re.compile(
    rf"\b(generated|created|written|authored)\s+(with|by)\b[^\n]*\b({_VENDORS})\b",
    re.I,
)
# pre-commit/merge/rebase autogenerated subjects that should not be rejected
ALLOW_PREFIX = ("Merge ", "Revert ", "fixup!", "squash!", "Reapply ")


def main() -> int:
    path = sys.argv[1] if len(sys.argv) > 1 else ".git/COMMIT_EDITMSG"
    try:
        with open(path, encoding="utf-8") as fh:
            msg = fh.read()
    except OSError as exc:
        print(f"commit-msg hook: cannot read {path}: {exc}")
        return 0  # never block on an infra failure

    lines = [ln for ln in msg.splitlines() if not ln.startswith("#")]
    subject = next((ln for ln in lines if ln.strip()), "")

    errs: list[str] = []
    if not subject.startswith(ALLOW_PREFIX) and not SUBJECT.match(subject):
        errs.append(
            f"subject is not a Conventional Commit: {subject!r}\n"
            f"      expected: <type>(<scope>): <subject>   (type one of: {TYPES})"
        )
    for ln in msg.splitlines():
        if ln.lstrip().startswith("#"):
            continue
        if AI.search(ln) or AI_FOOTER.search(ln):
            errs.append(f"AI attribution is forbidden (CLAUDE.md): {ln.strip()!r}")

    if errs:
        print("commit-msg blocked:")
        for e in errs:
            print("  - " + e)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
